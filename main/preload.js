'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch, ...a) => ipcRenderer.invoke(ch, ...a).then(r => { if (!r.ok) { const e = new Error(r.err); e.code = r.code; throw e; } return r.v; });
const on = (ch, f) => { const h = (_, d) => f(d); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); };

contextBridge.exposeInMainWorld('studio', {
  info: () => call('app:info'),
  settings: { get: () => call('settings:get'), set: p => call('settings:set', p) },
  caps: force => call('caps', force),
  titlebar: o => call('titlebar', o),
  open: (kind, multi) => call('dlg:open', { kind, multi }),
  folder: () => call('dlg:folder'),
  savePath: (name, ext, kind) => call('dlg:save', { name, ext, kind }),
  pathOf: file => webUtils.getPathForFile(file),
  dropped: paths => call('files:dropped', paths),
  probe: f => call('media:probe', f),
  thumbs: (f, d, n, h, s) => call('media:thumbs', f, d, n, h, s),
  frame: (f, t) => call('media:frame', f, t),
  peaks: (f, s, d, n) => call('media:peaks', f, s, d, n),
  proxy: (f, info) => call('media:proxy', f, info),
  reveal: p => call('fs:reveal', p),
  openPath: p => call('fs:open', p),
  writeTmp: (name, b64) => call('fs:writeTmp', name, b64),
  readText: p => call('fs:readText', p),
  writeText: (p, t) => call('fs:writeText', p, t),
  exists: p => call('fs:exists', p),
  outName: (base, suffix, ext) => call('fs:outName', base, suffix, ext),
  url: u => call('shell:url', u),
  project: { autosave: j => call('project:autosave', j), recover: () => call('project:recover'), clear: () => call('project:clearAutosave') },
  plan: req => call('job:plan', req),
  start: (req, meta) => call('job:start', req, meta),
  cancel: id => call('job:cancel', id),
  preview: (o, i, t) => call('job:preview', o, i, t),
  img: { analyze: src => call('img:analyze', src), upscale: (req, id) => call('img:upscale', req, id), cancel: () => call('img:cancel') },
  engines: { status: () => call('engines:status'), verify: () => call('engines:verify'), folder: () => call('engines:folder') },
  diag: f => call('diag:run', f),
  diagCached: () => call('diag:cached'),
  onJob: f => on('job:event', f),
  onProxy: f => on('proxy:progress', f),
  onImg: f => on('img:progress', f),
  onDiag: f => on('diag:progress', f),
  onEngines: f => on('engines:progress', f),
  onOpenFile: f => on('open:file', f),
});
